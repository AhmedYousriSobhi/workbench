"""The optional object store (issue 672, tier 3 of ADR 0078): one Garage node speaking S3.

Off by default and never in `--addons` or `all`: `benchctl up --with objectstore`. One unprivileged container, memory-limited,
class P6 (the first thing the governor stops). Slurm and login nodes get the endpoint and a key pair in `/run/workbench/objectstore/s3.env`
(read-only), so a job can `put` a file on one node and `get` it on another.

Generated under `compose/generated/` (gitignored, rewritten only when missing or different):
- `objectstore/garage.toml`: the server's configuration (no S3 key in it: Garage reads the default key from the environment).
- `secrets/objectstore/`: `access_key`, `secret_key`, `rpc_secret`, `metrics_token` (mode 600, never printed) and `s3.env`, the
  node-facing file (mode 644: the key pair is a simulation credential on the cluster network, like the shared munge key).
- `objectstore/data/`: the object data and metadata (the container runs as the invoking user, so the bind mounts are writable).
"""
from __future__ import annotations

import secrets as _secrets
from pathlib import Path

SERVICE = "objectstore"
IMAGE = "dxflrs/garage"
VERSION = "v2.5.0"  # ADR 0078 addendum: 69 MB image, runs as a non-root user, 6.4 MiB idle
LIMIT_MB = 384      # planning cap until measured with `benchctl measure` (200 MB upload showed 202 MiB incl. page cache)
S3_PORT, RPC_PORT, ADMIN_PORT = 3900, 3901, 3903
REGION = "garage"
BUCKET = "workbench"
DIR = "objectstore"                        # under compose/generated
SECRETS = "secrets/objectstore"            # under compose/generated
NODE_MOUNT = "/run/workbench/objectstore"  # where Slurm and login nodes see s3.env
HOST_PORT = 3900                           # published on 127.0.0.1 only
METRICS_FILE = "objectstore-metrics.token" # in secrets/prometheus, read by Prometheus


def image() -> str:
    return f"{IMAGE}:{VERSION}"


def endpoint() -> str:
    return f"http://{SERVICE}:{S3_PORT}"


def config_toml(rpc_secret: str, metrics_token: str) -> str:
    return "\n".join([
        "# GENERATED by `benchctl up` (benchctl/objectstore.py); do not edit.",
        'metadata_dir = "/meta"', 'data_dir = "/data"', 'db_engine = "lmdb"', "replication_factor = 1",
        f'rpc_bind_addr = "0.0.0.0:{RPC_PORT}"', f'rpc_secret = "{rpc_secret}"', "",
        "[s3_api]", f's3_region = "{REGION}"', f'api_bind_addr = "0.0.0.0:{S3_PORT}"', "",
        "[admin]", f'api_bind_addr = "0.0.0.0:{ADMIN_PORT}"', f'metrics_token = "{metrics_token}"', ""])


def s3_env(access_key: str, secret_key: str) -> str:
    """What a node sources: names the common S3 clients read."""
    return "\n".join([f"AWS_ENDPOINT_URL={endpoint()}", f"S3_ENDPOINT_URL={endpoint()}", f"AWS_DEFAULT_REGION={REGION}",
                      f"AWS_ACCESS_KEY_ID={access_key}", f"AWS_SECRET_ACCESS_KEY={secret_key}", f"WORKBENCH_S3_BUCKET={BUCKET}", ""])


def _write(path: Path, text: str, mode: int) -> None:
    if not path.is_file() or path.read_text() != text:
        path.write_text(text)
    path.chmod(mode)


def _keep(path: Path, make) -> str:
    """The stored value, or a new one written with mode 600: a key never changes under data that was written with it."""
    if path.is_file() and path.read_text().strip():
        return path.read_text().strip()
    value = make()
    path.write_text(value + "\n")
    path.chmod(0o600)
    return value


def prepare(root: Path) -> dict[str, str]:
    """Write the configuration and secrets; returns the values (for the compose wiring, never printed)."""
    sec = root / SECRETS
    sec.mkdir(parents=True, exist_ok=True)
    sec.chmod(0o755)  # nodes read s3.env here; every other file in it is 600
    cfg = root / DIR
    for sub in ("", "meta", "data"):
        (cfg / sub).mkdir(parents=True, exist_ok=True)
    vals = {"access_key": _keep(sec / "access_key", lambda: "GK" + _secrets.token_hex(12)),
            "secret_key": _keep(sec / "secret_key", lambda: _secrets.token_hex(32)),
            "rpc_secret": _keep(sec / "rpc_secret", lambda: _secrets.token_hex(32)),
            "metrics_token": _keep(sec / "metrics_token", lambda: _secrets.token_hex(24))}
    _write(cfg / "garage.toml", config_toml(vals["rpc_secret"], vals["metrics_token"]), 0o600)
    _write(sec / "s3.env", s3_env(vals["access_key"], vals["secret_key"]), 0o644)
    _write(sec / "server.env", "\n".join([f"GARAGE_DEFAULT_ACCESS_KEY={vals['access_key']}", f"GARAGE_DEFAULT_SECRET_KEY={vals['secret_key']}",
                                          f"GARAGE_DEFAULT_BUCKET={BUCKET}", ""]), 0o600)
    return vals


def wire(services: dict, uid: int, gid: int, clients: list[str]) -> None:
    """The service's command, user, mounts and port, and the read-only credentials on the named client services (Slurm nodes and
    logins); a no-op when the part is off. The secrets are made by `prepare` before `docker compose up` reads `env_file`."""
    svc = services.get(SERVICE)
    if svc is None:
        return
    svc.update({
        "image": image(), "user": f"{uid}:{gid}", "command": ["/garage", "server", "--single-node", "--default-bucket"],
        "env_file": [f"./{SECRETS}/server.env"],
        "volumes": [f"./{DIR}/garage.toml:/etc/garage.toml:ro", f"./{DIR}/meta:/meta", f"./{DIR}/data:/data"],
        "ports": [f"127.0.0.1:{HOST_PORT}:{S3_PORT}"]})
    for name in clients:
        if name in services:
            services[name]["volumes"].append(f"./{SECRETS}/s3.env:{NODE_MOUNT}/s3.env:ro")
