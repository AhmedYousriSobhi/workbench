"""Regenerate benchctl/slurm_msgtypes.py from the pinned Slurm release's own src/common/msg_type.h (issue 505, ADR 0042).

    curl -fsSLo slurm.tar.bz2 https://download.schedmd.com/slurm/slurm-VERSION.tar.bz2    # VERSION and SLURM_SHA256 are in images/node-base/Dockerfile
    echo "SHA256  slurm.tar.bz2" | sha256sum -c -
    tar -xjf slurm.tar.bz2 slurm-VERSION/src/common/msg_type.h slurm-VERSION/src/common/slurm_protocol_common.h
    python3 scripts/gen_slurm_msgtypes.py slurm-VERSION VERSION

Run it again whenever the pinned version changes; the numbers must come from that release, never from memory."""
import re
import sys
from pathlib import Path

src, version = Path(sys.argv[1]), sys.argv[2]
text = (src / "src/common/msg_type.h").read_text()
body = text[text.index("typedef enum {") + len("typedef enum {"):text.index("} slurm_msg_type_t;")]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.DOTALL)
types, nxt = {}, None
for item in body.split(","):
    m = re.match(r"\s*([A-Z0-9_]+)\s*(?:=\s*(\d+))?\s*$", item.replace("\n", " "))
    if not m:
        continue
    nxt = int(m[2]) if m[2] else (nxt + 1 if nxt is not None else 0)
    types[nxt] = m[1]
common = (src / "src/common/slurm_protocol_common.h").read_text()
major, minor = version.split(".")[:2]
rev = int(re.search(rf"SLURM_{major}_{minor}_PROTOCOL_VERSION MAKE_SLURM_VER\((\d+)\)", common)[1])
out = Path(__file__).resolve().parent.parent / "benchctl/slurm_msgtypes.py"
lines = [f'"""Slurm RPC message types of release {version}, generated by scripts/gen_slurm_msgtypes.py from its src/common/msg_type.h. Do not edit."""',
         f'VERSION = "{version}"', f"PROTOCOL = {rev << 8}  # the protocol version number in every message header of this release", "TYPES = {"]
lines += [f'    {k}: "{v}",' for k, v in sorted(types.items())]
out.write_text("\n".join(lines + ["}", ""]))
print(f"{len(types)} message types written to {out}")
